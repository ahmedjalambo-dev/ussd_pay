"""Generates the app's alpha-only Android icons.

Android draws these from the ALPHA channel only -- colour is thrown away -- so
an opaque, full-colour image (like the launcher icon) renders as a solid blob.
Both outputs are therefore white on transparent.

Outputs (committed; re-run only when the font or the launcher icon changes):
  android/app/src/main/res/drawable/ic_stat_ussd_pay.xml
      Notification small icon: a bold "#" (the USSD symbol) from the app's
      own IBM Plex Sans Bold, as a 24dp VectorDrawable.
  android/app/src/main/res/mipmap-*/ic_launcher_monochrome.png
      The adaptive launcher's "themed icon" layer (Android 13+), derived from
      the matching ic_launcher_foreground.png so the letters sit exactly where
      they do in the coloured icon. Re-run after regenerating launcher icons.

Usage (from the repo root):  python tool/generate_icons.py
Requires: fonttools, Pillow.
"""

from __future__ import annotations

import glob
import os
import sys
from collections import Counter

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "android", "app", "src", "main", "res")
FONT = os.path.join(
    ROOT, "assets", "fonts", "IBM_Plex_Sans", "static", "IBMPlexSans-Bold.ttf"
)

# Status-bar icons are 24dp; ~2dp padding keeps the glyph inside the live
# area so the system does not crop it.
VIEWPORT = 24.0
PADDING = 2.0


def notification_icon() -> str:
    font = TTFont(FONT)
    glyphs = font.getGlyphSet()
    glyph = glyphs["numbersign"]

    bounds = BoundsPen(glyphs)
    glyph.draw(bounds)
    x_min, y_min, x_max, y_max = bounds.bounds
    width, height = x_max - x_min, y_max - y_min

    box = VIEWPORT - 2 * PADDING
    scale = box / max(width, height)
    # Centre in the viewport; font units are y-up, VectorDrawable is y-down.
    dx = (VIEWPORT - width * scale) / 2 - x_min * scale
    dy = (VIEWPORT - height * scale) / 2 + y_max * scale

    svg = SVGPathPen(glyphs, ntos=lambda v: f"{v:.3f}".rstrip("0").rstrip("."))
    glyph.draw(TransformPen(svg, (scale, 0, 0, -scale, dx, dy)))

    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tool/generate_icons.py: do not edit by hand.\n"
        '     Notification small icon. Alpha-only by Android\'s rules, so it is\n'
        "     white on transparent; the system tints it. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="24dp"\n'
        '    android:height="24dp"\n'
        f'    android:viewportWidth="{VIEWPORT:g}"\n'
        f'    android:viewportHeight="{VIEWPORT:g}">\n'
        "    <path\n"
        '        android:fillColor="#FFFFFFFF"\n'
        f'        android:pathData="{svg.getCommands()}" />\n'
        "</vector>\n"
    )


def luminance(rgb: tuple[int, int, int]) -> float:
    r, g, b = rgb
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def monochrome_from(foreground_path: str) -> Image.Image:
    """White letters on transparent, alpha taken from the foreground's ink."""
    src = Image.open(foreground_path).convert("RGBA")
    opaque = Counter(p[:3] for p in src.getdata() if p[3] == 255)
    (bg, _), (ink, _) = opaque.most_common(2)
    bg_l, ink_l = luminance(bg), luminance(ink)
    span = abs(ink_l - bg_l) or 1.0

    out = Image.new("RGBA", src.size, (255, 255, 255, 0))
    pixels = []
    for r, g, b, a in src.getdata():
        if a == 0:
            pixels.append((255, 255, 255, 0))
            continue
        strength = min(1.0, max(0.0, abs(luminance((r, g, b)) - bg_l) / span))
        pixels.append((255, 255, 255, round(strength * a)))
    out.putdata(pixels)
    return out


def main() -> int:
    drawable = os.path.join(RES, "drawable", "ic_stat_ussd_pay.xml")
    with open(drawable, "w", encoding="utf-8", newline="\n") as f:
        f.write(notification_icon())
    print("wrote", os.path.relpath(drawable, ROOT))

    foregrounds = sorted(glob.glob(os.path.join(RES, "mipmap-*", "ic_launcher_foreground.png")))
    if not foregrounds:
        print("no ic_launcher_foreground.png found", file=sys.stderr)
        return 1
    for fg in foregrounds:
        target = os.path.join(os.path.dirname(fg), "ic_launcher_monochrome.png")
        monochrome_from(fg).save(target, optimize=True)
        print("wrote", os.path.relpath(target, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
