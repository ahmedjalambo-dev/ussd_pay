"""Generates every brand asset from one glyph: the bold "#" (the USSD symbol)
of IBM Plex Sans Bold, the app's own bundled font.

The "#" is USSD Pay's mark everywhere: notification, launcher icon, splash.
Its blue is the app's real `colorScheme.primary` (not the seed #2563EB --
fromSeed with contrastLevel 0.3 shifts it): #314377 light, #B4C5FF dark.
test/brand_colors_test.dart fails if the theme drifts from these values.

Outputs (committed; re-run only if the font, the colour or a size changes):
  android/app/src/main/res/
    drawable/ic_stat_ussd_pay.xml        notification small icon (24dp)
    drawable/ic_launcher_foreground.xml  adaptive icon: white "#"
    drawable/ic_launcher_monochrome.xml  adaptive icon: themed-icon layer
    values/ic_launcher_colors.xml        adaptive icon: #314377 background
    mipmap-anydpi-v26/ic_launcher.xml    adaptive icon (API 26+)
    mipmap-*dpi/ic_launcher.png          legacy icon (API 24-25)
  assets/branding/
    splash_mark_{light,dark}.png         splash, Android <= 11
    splash_mark_a12_{light,dark}.png     splash, Android 12+ (system API)
    branding_light.png / branding_dark.png
                                         "USSD Pay" wordmark for the splash's
                                         bottom branding slot (all versions)

After running, regenerate the native splash:
  dart run flutter_native_splash:create

Notification and monochrome icons are drawn by Android from their ALPHA
channel only -- colour is thrown away -- so they are white on transparent.

Usage (from the repo root):  python tool/generate_icons.py
Requires: fonttools, Pillow.
"""

from __future__ import annotations

import os
import sys

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "android", "app", "src", "main", "res")
BRANDING = os.path.join(ROOT, "assets", "branding")
FONT = os.path.join(
    ROOT, "assets", "fonts", "IBM_Plex_Sans", "static", "IBMPlexSans-Bold.ttf"
)

# AppTheme's colorScheme.primary / onPrimary per brightness, so the splash
# flows straight into the app's own filled buttons. The launcher icon cannot
# follow dark mode, so it uses the light pair everywhere.
PRIMARY_LIGHT = (0x31, 0x43, 0x77, 255)
ON_PRIMARY_LIGHT = (0xFF, 0xFF, 0xFF, 255)
PRIMARY_DARK = (0xB4, 0xC5, 0xFF, 255)
ON_PRIMARY_DARK = (0x06, 0x1D, 0x50, 255)
WHITE = (255, 255, 255, 255)

# Neutral wordmark inks, one per splash background (#F5F7FB / #0B1220), so
# the blue "#" stays the only colour on screen.
INK_LIGHT = (0x1C, 0x1C, 0x22, 255)
INK_DARK = (0xF5, 0xF4, 0xFB, 255)

# The mark's size relative to the coloured shape it sits on. 44dp of the
# adaptive icon's 72dp visible area; legacy and splash use the same ratio so
# the icon looks the same wherever it appears.
MARK_TO_SHAPE = 44 / 72

GENERATED = "Generated by tool/generate_icons.py: do not edit by hand."


# --- Vector (the glyph's real outline) -------------------------------------


def glyph_path(viewport: float, box: float) -> str:
    """SVG path data for the "#", scaled to fit [box] and centred in a square
    [viewport]. Font units are y-up; VectorDrawable is y-down."""
    font = TTFont(FONT)
    glyphs = font.getGlyphSet()
    glyph = glyphs["numbersign"]

    bounds = BoundsPen(glyphs)
    glyph.draw(bounds)
    x_min, y_min, x_max, y_max = bounds.bounds
    width, height = x_max - x_min, y_max - y_min

    scale = box / max(width, height)
    dx = (viewport - width * scale) / 2 - x_min * scale
    dy = (viewport - height * scale) / 2 + y_max * scale

    svg = SVGPathPen(glyphs, ntos=lambda v: f"{v:.3f}".rstrip("0").rstrip("."))
    glyph.draw(TransformPen(svg, (scale, 0, 0, -scale, dx, dy)))
    return svg.getCommands()


def vector(size_dp: int, viewport: float, path: str, comment: str) -> str:
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- {GENERATED}\n     {comment} -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{size_dp}dp"\n'
        f'    android:height="{size_dp}dp"\n'
        f'    android:viewportWidth="{viewport:g}"\n'
        f'    android:viewportHeight="{viewport:g}">\n'
        "    <path\n"
        '        android:fillColor="#FFFFFFFF"\n'
        f'        android:pathData="{path}" />\n'
        "</vector>\n"
    )


# --- Raster (legacy icon, splash) ------------------------------------------


def text_mask(text: str, max_w: int, max_h: int) -> Image.Image:
    """[text] as an alpha mask fitting within max_w x max_h px. Rendered
    large by FreeType from the same font file, cropped to the ink and scaled
    down, so the edges are clean at every size."""
    big = 1200
    font = ImageFont.truetype(FONT, big)
    canvas = Image.new("L", (big * (len(text) + 1), big * 2), 0)
    ImageDraw.Draw(canvas).text((big // 2, big // 4), text, fill=255, font=font)
    ink = canvas.crop(canvas.getbbox())
    scale = min(max_w / ink.width, max_h / ink.height)
    return ink.resize(
        (max(1, round(ink.width * scale)), max(1, round(ink.height * scale))),
        Image.LANCZOS,
    )


def mark_mask(size: int) -> Image.Image:
    """The "#" as an alpha mask whose longest side is [size] px."""
    return text_mask("#", size, size)


def wordmark(ink: tuple[int, int, int, int]) -> Image.Image:
    """"USSD Pay" on one line, centred on the 800x320 px canvas that the
    splash branding slot requires (treated as xxxhdpi: 200x80dp)."""
    img = Image.new("RGBA", (800, 320), (0, 0, 0, 0))
    mask = text_mask("USSD Pay", 560, 120)
    img.paste(
        Image.new("RGBA", mask.size, ink),
        ((img.width - mask.width) // 2, (img.height - mask.height) // 2),
        mask,
    )
    return img


def disc_with_mark(
    canvas_px: int, disc_px: int, disc, ink, ss: int = 4
) -> Image.Image:
    """A [disc]-coloured circle with an [ink] "#", centred on a transparent
    canvas. Drawn at [ss]x and downsampled for an anti-aliased circle edge."""
    big = canvas_px * ss
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    inset = (big - disc_px * ss) // 2
    ImageDraw.Draw(img).ellipse(
        (inset, inset, big - inset - 1, big - inset - 1), fill=disc
    )
    _paste_mark(img, round(disc_px * ss * MARK_TO_SHAPE), ink)
    return img.resize((canvas_px, canvas_px), Image.LANCZOS)


def mark_only(canvas_px: int, mark_px: int, ink) -> Image.Image:
    img = Image.new("RGBA", (canvas_px, canvas_px), (0, 0, 0, 0))
    _paste_mark(img, mark_px, ink)
    return img


def hex_of(rgba) -> str:
    return "#{:02X}{:02X}{:02X}".format(*rgba[:3])


def _paste_mark(img: Image.Image, mark_px: int, ink) -> None:
    mask = mark_mask(mark_px)
    x = (img.width - mask.width) // 2
    y = (img.height - mask.height) // 2
    img.paste(Image.new("RGBA", mask.size, ink), (x, y), mask)


# --- Writing ----------------------------------------------------------------


def write(path: str, text: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", os.path.relpath(path, ROOT))


def save(path: str, image: Image.Image) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    image.save(path, optimize=True)
    print("wrote", os.path.relpath(path, ROOT))


def main() -> int:
    # Notification: 24dp, ~2dp padding keeps the glyph in the status-bar
    # live area.
    write(
        os.path.join(RES, "drawable", "ic_stat_ussd_pay.xml"),
        vector(
            24,
            24,
            glyph_path(24, 20),
            "Notification small icon. Alpha-only by Android's rules, so it is\n"
            "     white on transparent; the system tints it.",
        ),
    )

    # Adaptive icon: 108dp layers, of which the launcher shows the middle
    # 72dp and may mask down to a 66dp circle. A 44dp mark stays clear of
    # every mask shape.
    launcher_path = glyph_path(108, 44)
    write(
        os.path.join(RES, "drawable", "ic_launcher_foreground.xml"),
        vector(108, 108, launcher_path, "Adaptive icon foreground: the white mark."),
    )
    write(
        os.path.join(RES, "drawable", "ic_launcher_monochrome.xml"),
        vector(
            108,
            108,
            launcher_path,
            "Adaptive icon monochrome layer (Android 13+ themed icons). Only its\n"
            "     alpha is used; the system recolours it from the wallpaper.",
        ),
    )
    write(
        os.path.join(RES, "values", "ic_launcher_colors.xml"),
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- {GENERATED}\n     AppTheme's light-mode colorScheme.primary. -->\n"
        "<resources>\n"
        f'    <color name="ic_launcher_background">{hex_of(PRIMARY_LIGHT)}</color>\n'
        "</resources>\n",
    )
    write(
        os.path.join(RES, "mipmap-anydpi-v26", "ic_launcher.xml"),
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- {GENERATED} -->\n"
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/ic_launcher_background" />\n'
        '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
        '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
        "</adaptive-icon>\n",
    )

    # Legacy icon for API 24-25 (minSdk 24): no adaptive layers there, so a
    # pre-composed disc with a small margin, like other round legacy icons.
    for density, px in {
        "mdpi": 48,
        "hdpi": 72,
        "xhdpi": 96,
        "xxhdpi": 144,
        "xxxhdpi": 192,
    }.items():
        save(
            os.path.join(RES, f"mipmap-{density}", "ic_launcher.png"),
            disc_with_mark(px, round(px * 44 / 48), PRIMARY_LIGHT, WHITE),
        )

    # Splash, per mode, in the app's primary / onPrimary so it flows into the
    # app's own colours. Android <= 11: the image is treated as xxxhdpi (4x),
    # so 768 px is a 192dp disc in the middle of the screen. Android 12+: the
    # system draws the disc itself (icon_background_color, in
    # flutter_native_splash.yaml) over the middle 768 px of the 1152 px
    # image, so only the mark goes in the image.
    for mode, disc, ink in (
        ("light", PRIMARY_LIGHT, ON_PRIMARY_LIGHT),
        ("dark", PRIMARY_DARK, ON_PRIMARY_DARK),
    ):
        save(
            os.path.join(BRANDING, f"splash_mark_{mode}.png"),
            disc_with_mark(768, 768, disc, ink),
        )
        save(
            os.path.join(BRANDING, f"splash_mark_a12_{mode}.png"),
            mark_only(1152, round(768 * MARK_TO_SHAPE), ink),
        )

    # The name, in the splash's bottom branding slot -- the only place the
    # Android 12+ system splash allows anything besides the centred icon.
    save(os.path.join(BRANDING, "branding_light.png"), wordmark(INK_LIGHT))
    save(os.path.join(BRANDING, "branding_dark.png"), wordmark(INK_DARK))
    return 0


if __name__ == "__main__":
    sys.exit(main())
